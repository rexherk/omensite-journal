-- Omensite Journal: initial managed PostgreSQL schema.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    password_salt TEXT NOT NULL,
    timezone TEXT NOT NULL DEFAULT 'America/New_York',
    news_window_minutes INTEGER NOT NULL DEFAULT 15,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    csrf TEXT NOT NULL,
    expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('personal', 'prop', 'sim')),
    starting_balance DOUBLE PRECISION NOT NULL DEFAULT 0,
    daily_loss_limit DOUBLE PRECISION,
    trailing_drawdown DOUBLE PRECISION,
    profit_target DOUBLE PRECISION,
    UNIQUE (user_id, name)
);
CREATE TABLE IF NOT EXISTS checklist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    label TEXT NOT NULL,
    position INTEGER NOT NULL,
    active INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
    instrument TEXT NOT NULL,
    asset_class TEXT NOT NULL CHECK (asset_class IN ('future', 'stock')),
    direction TEXT NOT NULL CHECK (direction IN ('long', 'short')),
    fees DOUBLE PRECISION NOT NULL DEFAULT 0,
    stop DOUBLE PRECISION,
    target DOUBLE PRECISION,
    session TEXT,
    kill_zone TEXT,
    macro_window TEXT,
    htf_bias TEXT,
    draw TEXT,
    premium TEXT,
    range_high DOUBLE PRECISION,
    range_low DOUBLE PRECISION,
    setup TEXT,
    grade TEXT,
    auto_grade TEXT,
    grade_manual INTEGER NOT NULL DEFAULT 0,
    went_right TEXT,
    went_wrong TEXT,
    lesson TEXT,
    notes TEXT,
    emotion_before TEXT,
    emotion_after TEXT,
    confidence INTEGER,
    followed_plan INTEGER CHECK (followed_plan IS NULL OR followed_plan IN (0, 1)),
    mae_price DOUBLE PRECISION,
    mfe_price DOUBLE PRECISION,
    opened_at TEXT,
    closed_at TEXT,
    opened_local TEXT,
    closed_local TEXT,
    closed_day TEXT,
    is_closed INTEGER NOT NULL CHECK (is_closed IN (0, 1)),
    net_pnl DOUBLE PRECISION,
    gross_pnl DOUBLE PRECISION,
    points DOUBLE PRECISION,
    ticks DOUBLE PRECISION,
    r_multiple DOUBLE PRECISION,
    planned_r DOUBLE PRECISION,
    hold_seconds INTEGER,
    risk_dollars DOUBLE PRECISION,
    mae_points DOUBLE PRECISION,
    mfe_points DOUBLE PRECISION,
    mae_dollars DOUBLE PRECISION,
    mfe_dollars DOUBLE PRECISION,
    left_on_table DOUBLE PRECISION,
    avg_entry DOUBLE PRECISION,
    avg_exit DOUBLE PRECISION,
    qty_entered DOUBLE PRECISION,
    qty_exited DOUBLE PRECISION,
    open_qty DOUBLE PRECISION,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS legs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id INTEGER NOT NULL REFERENCES trades(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('entry', 'exit')),
    qty DOUBLE PRECISION NOT NULL,
    price DOUBLE PRECISION NOT NULL,
    filled_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS trade_tags (
    trade_id INTEGER NOT NULL REFERENCES trades(id) ON DELETE CASCADE,
    tag TEXT NOT NULL,
    PRIMARY KEY (trade_id, tag)
);
CREATE TABLE IF NOT EXISTS trade_mistakes (
    trade_id INTEGER NOT NULL REFERENCES trades(id) ON DELETE CASCADE,
    mistake TEXT NOT NULL,
    PRIMARY KEY (trade_id, mistake)
);
CREATE TABLE IF NOT EXISTS trade_checks (
    trade_id INTEGER NOT NULL REFERENCES trades(id) ON DELETE CASCADE,
    item_id INTEGER NOT NULL REFERENCES checklist_items(id) ON DELETE CASCADE,
    checked INTEGER NOT NULL,
    PRIMARY KEY (trade_id, item_id)
);
CREATE TABLE IF NOT EXISTS screenshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    trade_id INTEGER NOT NULL REFERENCES trades(id) ON DELETE CASCADE,
    slot TEXT NOT NULL CHECK (slot IN ('htf', 'entry', 'after_exit')),
    filename TEXT NOT NULL,
    markup_json TEXT NOT NULL DEFAULT '[]',
    created_at TEXT NOT NULL,
    UNIQUE (trade_id, slot)
);
CREATE TABLE IF NOT EXISTS days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day TEXT NOT NULL,
    bias TEXT,
    key_levels TEXT,
    draw TEXT,
    news_to_watch TEXT,
    eod_review TEXT,
    UNIQUE (user_id, day)
);
CREATE TABLE IF NOT EXISTS playbooks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    setup TEXT,
    rules TEXT,
    example_notes TEXT,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS playbook_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    playbook_id INTEGER NOT NULL REFERENCES playbooks(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS watchlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    symbol TEXT NOT NULL,
    UNIQUE (user_id, symbol)
);
CREATE TABLE IF NOT EXISTS password_resets (
    token TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS earnings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    symbol TEXT NOT NULL,
    when_at TEXT NOT NULL,
    note TEXT
);
CREATE TABLE IF NOT EXISTS news_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    when_utc TEXT NOT NULL,
    impact TEXT NOT NULL CHECK (impact IN ('high', 'medium', 'low')),
    category TEXT NOT NULL CHECK (category IN ('economic', 'holiday', 'early_close')),
    actual TEXT,
    forecast TEXT,
    previous TEXT,
    note TEXT
);
CREATE INDEX IF NOT EXISTS idx_trades_user ON trades (user_id, opened_at);
CREATE INDEX IF NOT EXISTS idx_news_when ON news_events (when_utc);
CREATE TABLE IF NOT EXISTS media_blobs (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    content BYTEA NOT NULL,
    PRIMARY KEY (user_id, filename)
);

